/** Komunikaty z parametrami. Zwraca null, gdy wzorzec nie pasuje. */
export function translateMore(message: string): string | null {
  const imported = message.match(/^Dodano (\d+), zaktualizowano (\d+), pominięto (\d+)\.$/);
  if (imported) return `Added ${imported[1]}, updated ${imported[2]}, skipped ${imported[3]}.`;
  const synced = message.match(/^Synchronizacja zakończona\. Pominięto (\d+), bo te książki są już w katalogu pod innym wpisem\.$/);
  if (synced) return `Sync finished. Skipped ${synced[1]} because these books are already in the catalog under another entry.`;
  const restore = message.match(/^Nie można przywrócić: w katalogu jest już „(.+)”\.$/);
  if (restore) return `Cannot restore: “${restore[1]}” is already in the catalog.`;
  const restoreIsbn = message.match(/^Nie można przywrócić: ISBN (.+) ma już inna książka\.$/);
  if (restoreIsbn) return `Cannot restore: another book already has ISBN ${restoreIsbn[1]}.`;
  const restoreFile = message.match(/^Nie można przywrócić: plik (.+) jest już przy książce „(.+)”\.$/);
  if (restoreFile) return `Cannot restore: the file ${restoreFile[1]} is already attached to “${restoreFile[2]}”.`;
  const sameName = message.match(/^W folderze książki jest już inny plik o nazwie „(.+)”\.$/);
  if (sameName) return `The book folder already has a different file named “${sameName[1]}”.`;
  const remote = message.match(/^Nie można odczytać library\.json z folderu synchronizacji: (.+)$/);
  if (remote) return `Cannot read library.json in the sync folder: ${remote[1]}`;
  return null;
}
